"""C++ language handler for AutoPerf v2.

The handler generates a self-contained harness around the user's kernel
source.  The harness supports two run modes:

    ./binary --test   Run correctness checks, exit 0 on success.
    ./binary --bench  Run a tight benchmark loop, emit JSON on stdout.

The kernel source is written to a file and ``#include``d by the harness so
that the optimiser can see the implementation.  The header (if it exists)
is also included so that the harness can call the kernel's public API.

The harness is generated by parsing the actual function signature from the
kernel source, so it works with any kernel that follows standard C/C++
function declaration conventions.
"""

