@dataclass
class FuncParam:
    """A single parsed function parameter."""
    full_type: str   # e.g. "const float*" -- the type WITHOUT the name
    name: str        # e.g. "data"
    is_pointer: bool
    is_const: bool
    base_type: str   # e.g. "float"
    is_size: bool    # True if the type is size_t / int / unsigned and name
                     # hints at a count/length/size/n


@dataclass
class FuncSig:
    """A parsed function signature."""
    return_type: str      # e.g. "float" or "void"
    name: str             # e.g. "reduce"
    params: List[FuncParam]
    returns_value: bool   # True when return_type is not void


_SIZE_NAMES = re.compile(r'^(n|N|sz|size|len|length|count|rows|cols|dim|M|K)$')
_SIZE_TYPES = {'size_t', 'int', 'unsigned', 'unsigned int', 'long', 'unsigned long'}


def _parse_param(raw: str) -> FuncParam:
    """Parse a single C/C++ parameter declaration like ``const float* data``."""
    raw = raw.strip()
    is_const = 'const' in raw
    is_pointer = '*' in raw

    # Normalise: strip const, *, &
    cleaned = raw.replace('const ', '').replace('const', '').replace('*', ' ').replace('&', ' ').strip()
    parts = cleaned.split()
    if len(parts) >= 2:
        name = parts[-1]
        base_type = ' '.join(parts[:-1])
    elif len(parts) == 1:
        # unnamed parameter -- synthesise a name
        name = '_unnamed'
        base_type = parts[0]
    else:
        name = '_unnamed'
        base_type = 'int'

    # Reconstruct the type string (without the parameter name)
    type_str = ''
    if is_const:
        type_str = 'const '
    type_str += base_type
    if is_pointer:
        type_str += '*'

    is_size = (base_type in _SIZE_TYPES) and (not is_pointer) and bool(_SIZE_NAMES.match(name))

    return FuncParam(
        full_type=type_str,
        name=name,
        is_pointer=is_pointer,
        is_const=is_const,
        base_type=base_type,
        is_size=is_size,
    )


def parse_function_signature(source: str) -> Optional[FuncSig]:
    """Find the first non-static, non-inline-helper function in *source*.

    Returns ``None`` if no suitable function is found.
    """
    # Match:  <return_type> <name>(<params>) {
    # We skip lines starting with 'static' or '#'.
    pattern = re.compile(
        r'^\s*'                          # leading whitespace
        r'(?!static\b)'                  # not static
        r'(?!#)'                         # not preprocessor
        r'([\w\s\*&:]+?)'               # return type  (group 1)
        r'\b(\w+)\s*'                    # function name (group 2)
        r'\(([^)]*)\)\s*\{',             # parameters   (group 3)
        re.MULTILINE,
    )
    for m in pattern.finditer(source):
        ret_type = m.group(1).strip()
        fname = m.group(2).strip()
        params_raw = m.group(3).strip()

        # Skip main, helpers, constructors
        if fname in ('main', 'now_ns', 'run_tests', 'run_bench'):
            continue

        params = []
        if params_raw:
            for p in params_raw.split(','):
                params.append(_parse_param(p))

        returns_value = ret_type != 'void'

        return FuncSig(
            return_type=ret_type,
            name=fname,
            params=params,
            returns_value=returns_value,
        )
    return None


