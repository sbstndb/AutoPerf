HARNESS_TEMPLATE = r"""
// Auto-generated by AutoPerf v2 -- do not edit.
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cmath>
#include <cstddef>
#include <vector>
#include <numeric>
#include <random>
#include <string>
#include <stdexcept>
#include <time.h>

{header_include}

// Include the kernel implementation directly so the compiler can inline.
{kernel_include}

// ---- helpers ---------------------------------------------------------------

static inline double now_ns() {{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec * 1e9 + (double)ts.tv_nsec;
}}

// ---- test mode -------------------------------------------------------------

static int run_tests() {{
{test_body}
    return 0;  // all passed
}}

// ---- bench mode ------------------------------------------------------------

static void run_bench() {{
{bench_setup}

    // Auto-calibrate: find iteration count that takes >= 0.5s,
    // capped at {max_bench_iters} iters.
    int _autoperf_N = 1;
    for (;;) {{
        double _cal_start = now_ns();
        for (int _i = 0; _i < _autoperf_N; ++_i) {{
            {bench_call};
            asm volatile("" ::: "memory");
        }}
        double _cal_elapsed = now_ns() - _cal_start;
        if (_cal_elapsed >= 5e8 || _autoperf_N >= {max_bench_iters}) break;
        // Scale up: target 1s total
        int _next = (int)((1e9 / _cal_elapsed) * _autoperf_N);
        if (_next <= _autoperf_N) _next = _autoperf_N * 2;
        if (_next > {max_bench_iters}) _next = {max_bench_iters};
        _autoperf_N = _next;
    }}

    // Warm-up with the calibrated count (small fraction)
    int _warmup = _autoperf_N < 100 ? _autoperf_N : 100;
    for (int _w = 0; _w < _warmup; ++_w) {{
        {bench_call};
        asm volatile("" ::: "memory");
    }}

    // Timed loop
    double start = now_ns();
    for (int _i = 0; _i < _autoperf_N; ++_i) {{
        {bench_call};
        asm volatile("" ::: "memory");
    }}
    double end = now_ns();

    double ns_per_op = (end - start) / (double)_autoperf_N;
    printf("{{\"ns_per_op\": %.2f, \"iterations\": %d}}\n", ns_per_op, _autoperf_N);

{bench_teardown}
}}

// ---- main ------------------------------------------------------------------

int main(int argc, char** argv) {{
    if (argc < 2) {{
        fprintf(stderr, "Usage: %s --test | --bench\\n", argv[0]);
        return 2;
    }}
    if (std::string(argv[1]) == "--test")  return run_tests();
    if (std::string(argv[1]) == "--bench") {{ run_bench(); return 0; }}
    fprintf(stderr, "Unknown flag: %s\\n", argv[1]);
    return 2;
}}
"""


class CppHandler(LanguageHandler):
    """Compile and benchmark C++ kernels with raw g++."""

    COMPILER = "g++"
    STD_FLAG = "-std=c++17"
    LANGUAGE_NAME = "C++"

    def __init__(self, config):
        super().__init__(config)
        self._binary_path = os.path.join(self._workdir, "autoperf_harness")
        self._harness_path = os.path.join(self._workdir, "harness.cpp")
        self._kernel_path = os.path.join(self._workdir, "kernel.cpp")

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _find_header(self) -> str | None:
        """Try to locate the matching header for the configured kernel_path."""
        kp = Path(self.config.kernel_path)
        candidates = [
            kp.parent.parent / "include" / kp.with_suffix(".hpp").name,
            kp.parent / kp.with_suffix(".hpp").name,
            kp.parent / kp.with_suffix(".h").name,
            kp.parent.parent / "include" / kp.with_suffix(".h").name,
        ]
        for c in candidates:
            if c.is_file():
                return str(c)
        return None

    def _generate_harness(
        self,
        kernel_code: str,
        header_path: str | None = None,
    ) -> str:
        """Build the harness C++ source by parsing the kernel's function signature."""

        # Parse the kernel's actual function signature
        sig = parse_function_signature(kernel_code)

        if sig is None:
            spec = {
                'test_body': '    fprintf(stderr, "No function found in kernel source.\\n");\n',
                'bench_setup': '    // No auto-detected benchmark setup.',
                'bench_call': '(void)0',
                'bench_teardown': '',
            }
        else:
            spec = _generate_test_and_bench(sig)

        # Build include directives
        header_include = ""
        if header_path:
            hdr_dest = os.path.join(self._workdir, os.path.basename(header_path))
            with open(header_path) as f:
                hdr_contents = f.read()
            with open(hdr_dest, "w") as f:
                f.write(hdr_contents)
            header_include = f'#include "{os.path.basename(header_path)}"'

        kernel_include = f'#include "{os.path.basename(self._kernel_path)}"'

        harness = HARNESS_TEMPLATE.format(
            header_include=header_include,
            kernel_include=kernel_include,
            test_body=textwrap.indent(spec["test_body"], "    "),
            bench_setup=textwrap.indent(spec["bench_setup"], "    "),
            bench_call=spec["bench_call"],
            bench_teardown=spec.get("bench_teardown", ""),
            max_bench_iters=10000000,
        )
        return harness

    def _run_sandboxed(self, args: list[str], **kwargs) -> subprocess.CompletedProcess:
        """Run a command under sandbox constraints."""
        cmd = self._sandbox_prefix() + args
        return subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            preexec_fn=self._ulimit_preexec(),
            **kwargs,
        )

