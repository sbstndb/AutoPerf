def _generate_test_and_bench(sig: FuncSig) -> dict[str, str]:
    """Generate test_body, bench_setup, bench_call, bench_teardown for *sig*.

    This handles the four known kernel patterns:
      - reduce(const float* data, size_t n) -> float
      - dot(const float* a, const float* b, size_t n) -> float
      - axpy(float a, const float* x, float* y, size_t n) -> void
      - matmul(const float* A, const float* B, float* C, size_t N) -> void

    And falls back to a reasonable generic pattern for unknown signatures.
    """
    name = sig.name

    # Classify parameters
    scalar_params = [p for p in sig.params if not p.is_pointer and not p.is_size]
    size_params = [p for p in sig.params if p.is_size]
    const_array_params = [p for p in sig.params if p.is_pointer and p.is_const]
    mut_array_params = [p for p in sig.params if p.is_pointer and not p.is_const]

    # Determine the size variable name (use the first size param, or "N")
    size_name = size_params[0].name if size_params else 'N'

    # ----- generate test body -----
    test_lines = []
    bench_setup_lines = []
    bench_call = ''
    bench_teardown = ''

    if sig.returns_value and not mut_array_params:
        # Pattern: returns a scalar, no output arrays (reduce, dot)
        test_size = 1024

        test_lines.append('{')
        test_lines.append(f'    const size_t {size_name} = {test_size};')

        # Allocate const input arrays
        for p in const_array_params:
            test_lines.append(f'    std::vector<{p.base_type}> _vec_{p.name}({size_name});')
            test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) _vec_{p.name}[_i] = ({p.base_type})(_i + 1);')

        # Scalar params get fixed test values
        for p in scalar_params:
            test_lines.append(f'    {p.full_type} {p.name} = ({p.base_type})2.5;')

        # Build the call expression
        call_args = []
        for p in sig.params:
            if p.is_size:
                call_args.append(size_name)
            elif p.is_pointer:
                call_args.append(f'_vec_{p.name}.data()')
            else:
                call_args.append(p.name)

        call_expr = f'{name}({", ".join(call_args)})'

        # Compute reference with a naive loop
        test_lines.append(f'    // Naive reference')
        test_lines.append(f'    {sig.return_type} expected = 0;')

        if len(const_array_params) == 1:
            # reduce-style: sum all elements
            p = const_array_params[0]
            test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) expected += _vec_{p.name}[_i];')
        elif len(const_array_params) == 2:
            # dot-style: sum of products
            p0, p1 = const_array_params[0], const_array_params[1]
            test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) expected += _vec_{p0.name}[_i] * _vec_{p1.name}[_i];')

        test_lines.append(f'    {sig.return_type} actual = {call_expr};')
        test_lines.append(f'    if (std::fabs((double)(expected - actual)) > 1e-1) {{')
        test_lines.append(f'        fprintf(stderr, "FAIL {name}: expected %f got %f\\n", (double)expected, (double)actual);')
        test_lines.append(f'        return 1;')
        test_lines.append(f'    }}')
        test_lines.append('}')

        # Also test with size 0
        test_lines.append('{')
        test_lines.append(f'    const size_t {size_name} = 0;')
        for p in const_array_params:
            test_lines.append(f'    std::vector<{p.base_type}> _vec_{p.name};')
        for p in scalar_params:
            test_lines.append(f'    {p.full_type} {p.name} = ({p.base_type})1.0;')
        test_lines.append(f'    {sig.return_type} actual = {call_expr};')
        test_lines.append(f'    if (std::fabs((double)actual) > 1e-6) {{')
        test_lines.append(f'        fprintf(stderr, "FAIL {name}(empty): expected 0 got %f\\n", (double)actual);')
        test_lines.append(f'        return 1;')
        test_lines.append(f'    }}')
        test_lines.append('}')

        # Bench setup
        bench_size = '1 << 20'
        bench_setup_lines.append(f'const size_t {size_name} = {bench_size};')
        for p in const_array_params:
            bench_setup_lines.append(f'std::vector<{p.base_type}> _vec_{p.name}({size_name});')
            bench_setup_lines.append(f'{{ std::mt19937 _rng(42); std::uniform_real_distribution<{p.base_type}> _d(0,1);')
            bench_setup_lines.append(f'  for (auto& _v : _vec_{p.name}) _v = _d(_rng); }}')
        for p in scalar_params:
            bench_setup_lines.append(f'{p.full_type} {p.name} = ({p.base_type})2.5;')
        bench_setup_lines.append(f'volatile {sig.return_type} _sink;')
        bench_call = f'_sink = {call_expr}'
        bench_teardown = '    (void)_sink;'

    elif not sig.returns_value and mut_array_params:
        # Pattern: void function with output array(s) (axpy, matmul)

        # Detect matmul pattern: 2 const arrays + 1 mut array + 1 size = square matmul
        is_matmul = (len(const_array_params) == 2 and len(mut_array_params) == 1
                     and len(size_params) == 1 and name in ('matmul', 'gemm', 'sgemm', 'matrix_multiply'))

        if is_matmul:
            _gen_matmul(sig, size_name, const_array_params, mut_array_params, scalar_params, test_lines, bench_setup_lines)
            call_args = []
            for p in sig.params:
                if p.is_size:
                    call_args.append(size_name)
                elif p.is_pointer:
                    call_args.append(f'_vec_{p.name}.data()')
                else:
                    call_args.append(p.name)
            call_expr = f'{name}({", ".join(call_args)})'
            bench_call = call_expr
        else:
            # Generic void-with-output: axpy-style
            test_size = 1024

            test_lines.append('{')
            test_lines.append(f'    const size_t {size_name} = {test_size};')

            for p in const_array_params:
                test_lines.append(f'    std::vector<{p.base_type}> _vec_{p.name}({size_name});')
                test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) _vec_{p.name}[_i] = ({p.base_type})(_i + 1);')

            for p in mut_array_params:
                test_lines.append(f'    std::vector<{p.base_type}> _vec_{p.name}({size_name});')
                test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) _vec_{p.name}[_i] = ({p.base_type})(_i * 0.5f);')

            # Reference copy for mut arrays
            for p in mut_array_params:
                test_lines.append(f'    std::vector<{p.base_type}> _ref_{p.name}(_vec_{p.name});')

            for p in scalar_params:
                test_lines.append(f'    {p.full_type} {p.name} = ({p.base_type})2.0;')

            call_args = []
            for p in sig.params:
                if p.is_size:
                    call_args.append(size_name)
                elif p.is_pointer:
                    call_args.append(f'_vec_{p.name}.data()')
                else:
                    call_args.append(p.name)
            call_expr = f'{name}({", ".join(call_args)})'

            test_lines.append(f'    // Compute naive reference')
            # For axpy: y[i] = a*x[i] + y[i]
            if name == 'axpy' and len(scalar_params) == 1 and len(const_array_params) == 1 and len(mut_array_params) == 1:
                a_name = scalar_params[0].name
                x_name = const_array_params[0].name
                y_name = mut_array_params[0].name
                test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i)')
                test_lines.append(f'        _ref_{y_name}[_i] = {a_name} * _vec_{x_name}[_i] + _ref_{y_name}[_i];')
            else:
                # Generic: we cannot compute a reference, so just run and don't crash
                test_lines.append(f'    // (generic: no reference computation, just check it does not crash)')

            test_lines.append(f'    {call_expr};')

            # Check output vs reference (only if we computed one)
            if name == 'axpy' and len(scalar_params) == 1 and len(const_array_params) == 1 and len(mut_array_params) == 1:
                y_name = mut_array_params[0].name
                test_lines.append(f'    for (size_t _i = 0; _i < {size_name}; ++_i) {{')
                test_lines.append(f'        if (std::fabs(_vec_{y_name}[_i] - _ref_{y_name}[_i]) > 1e-2f) {{')
                test_lines.append(f'            fprintf(stderr, "FAIL {name}[%zu]: expected %f got %f\\n", _i, (double)_ref_{y_name}[_i], (double)_vec_{y_name}[_i]);')
                test_lines.append(f'            return 1;')
                test_lines.append(f'        }}')
                test_lines.append(f'    }}')

            test_lines.append('}')

            # Bench setup
            bench_size = '1 << 20'
            bench_setup_lines.append(f'const size_t {size_name} = {bench_size};')
            for p in const_array_params:
                bench_setup_lines.append(f'std::vector<{p.base_type}> _vec_{p.name}({size_name});')
                bench_setup_lines.append(f'{{ std::mt19937 _rng(42); std::uniform_real_distribution<{p.base_type}> _d(0,1);')
                bench_setup_lines.append(f'  for (auto& _v : _vec_{p.name}) _v = _d(_rng); }}')
            for p in mut_array_params:
                bench_setup_lines.append(f'std::vector<{p.base_type}> _vec_{p.name}({size_name}, 0);')
            for p in scalar_params:
                bench_setup_lines.append(f'{p.full_type} {p.name} = ({p.base_type})2.5;')
            bench_call = call_expr

    else:
        # Unknown pattern: generate a minimal harness
        test_lines.append(f'fprintf(stderr, "No auto-detected tests for {name}.\\n");')
        bench_setup_lines.append('// No auto-detected benchmark setup.')
        bench_call = '(void)0'

    return {
        'test_body': '\n'.join(test_lines),
        'bench_setup': '\n'.join(bench_setup_lines),
        'bench_call': bench_call,
        'bench_teardown': bench_teardown,
    }


def _gen_matmul(sig, size_name, const_array_params, mut_array_params, scalar_params,
                test_lines, bench_setup_lines):
    """Generate test + bench setup specifically for square matmul."""
    name = sig.name
    A_name = const_array_params[0].name
    B_name = const_array_params[1].name
    C_name = mut_array_params[0].name
    base = const_array_params[0].base_type

    # --- Test: 2x2 identity * matrix ---
    test_lines.append('{')
    test_lines.append(f'    const size_t {size_name} = 2;')
    test_lines.append(f'    std::vector<{base}> _vec_{A_name} = {{1,0, 0,1}};')
    test_lines.append(f'    std::vector<{base}> _vec_{B_name} = {{5,6, 7,8}};')
    test_lines.append(f'    std::vector<{base}> _vec_{C_name}(4, 0.0f);')
    for p in scalar_params:
        test_lines.append(f'    {p.full_type} {p.name} = ({p.base_type})1.0;')

    call_args = []
    for p in sig.params:
        if p.is_size:
            call_args.append(size_name)
        elif p.is_pointer:
            call_args.append(f'_vec_{p.name}.data()')
        else:
            call_args.append(p.name)
    call_expr = f'{name}({", ".join(call_args)})'

    test_lines.append(f'    {call_expr};')
    test_lines.append(f'    {base} expected[] = {{5,6, 7,8}};')
    test_lines.append(f'    for (size_t _i = 0; _i < 4; ++_i) {{')
    test_lines.append(f'        if (std::fabs(_vec_{C_name}[_i] - expected[_i]) > 1e-4f) {{')
    test_lines.append(f'            fprintf(stderr, "FAIL {name}[%zu]: expected %f got %f\\n", _i, (double)expected[_i], (double)_vec_{C_name}[_i]);')
    test_lines.append(f'            return 1;')
    test_lines.append(f'        }}')
    test_lines.append(f'    }}')
    test_lines.append('}')

    # --- Test: 3x3 known multiplication ---
    test_lines.append('{')
    test_lines.append(f'    const size_t {size_name} = 3;')
    test_lines.append(f'    std::vector<{base}> _vec_{A_name} = {{1,2,3, 4,5,6, 7,8,9}};')
    test_lines.append(f'    std::vector<{base}> _vec_{B_name} = {{9,8,7, 6,5,4, 3,2,1}};')
    test_lines.append(f'    std::vector<{base}> _vec_{C_name}(9, 0.0f);')
    for p in scalar_params:
        test_lines.append(f'    {p.full_type} {p.name} = ({p.base_type})1.0;')
    test_lines.append(f'    {call_expr};')
    test_lines.append(f'    // Reference: naive matmul')
    test_lines.append(f'    {base} ref[9] = {{0}};')
    test_lines.append(f'    for (size_t i = 0; i < {size_name}; ++i)')
    test_lines.append(f'        for (size_t j = 0; j < {size_name}; ++j)')
    test_lines.append(f'            for (size_t k = 0; k < {size_name}; ++k)')
    test_lines.append(f'                ref[i*{size_name}+j] += _vec_{A_name}[i*{size_name}+k] * _vec_{B_name}[k*{size_name}+j];')

    # Wait -- we already mutated _vec_A and _vec_B data? No, those are const.
    # But _vec_C was written. And we used the vectors for reference computation.
    # Actually reference needs original A and B which are const_array, so the
    # vector data is unchanged. But we need to re-read _vec_A, _vec_B.
    # Actually the call modifies C only. A and B are const. So ref computation
    # using _vec_A and _vec_B after the call is fine.
    # BUT we did the call first, and THEN compute ref -- that means _vec_A, _vec_B
    # are still fine (const). But _vec_C is the output. ref uses A,B source data.
    # Wait, the ref computation reads _vec_A and _vec_B -- but those are the SAME
    # vectors we passed to the function. Since they're const in the function, the
    # data should be unchanged. So this is correct.
    # Actually, let me reorder: compute ref BEFORE the call for safety.
    # Let me just put ref first and use A_init/B_init copies.
    # Actually, simplify: compute ref from the initializer values directly.

    # The approach above has a subtle issue: we compute ref AFTER the call using
    # _vec_A and _vec_B which are the same vectors. Since A and B are const in
    # the kernel, this should be fine. Let me keep it simple.

    test_lines.append(f'    for (size_t _i = 0; _i < 9; ++_i) {{')
    test_lines.append(f'        if (std::fabs(_vec_{C_name}[_i] - ref[_i]) > 1e-2f) {{')
    test_lines.append(f'            fprintf(stderr, "FAIL {name}(3x3)[%zu]: expected %f got %f\\n", _i, (double)ref[_i], (double)_vec_{C_name}[_i]);')
    test_lines.append(f'            return 1;')
    test_lines.append(f'        }}')
    test_lines.append(f'    }}')
    test_lines.append('}')

    # Bench setup
    bench_setup_lines.append(f'const size_t {size_name} = 128;')
    bench_setup_lines.append(f'std::vector<{base}> _vec_{A_name}({size_name}*{size_name});')
    bench_setup_lines.append(f'std::vector<{base}> _vec_{B_name}({size_name}*{size_name});')
    bench_setup_lines.append(f'std::vector<{base}> _vec_{C_name}({size_name}*{size_name}, 0.0f);')
    bench_setup_lines.append(f'{{ std::mt19937 _rng(42); std::uniform_real_distribution<{base}> _d(-1,1);')
    bench_setup_lines.append(f'  for (auto& _v : _vec_{A_name}) _v = _d(_rng);')
    bench_setup_lines.append(f'  for (auto& _v : _vec_{B_name}) _v = _d(_rng); }}')


